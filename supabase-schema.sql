-- MY FINANCE PRO — SUPABASE DATABASE & SECURITY
-- Jalankan sekali dalam Supabase > SQL Editor.

create table if not exists public.user_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.finance_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  record_month text not null,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint finance_records_user_month_unique unique (user_id, record_month),
  constraint finance_records_month_format check (record_month ~ '^[0-9]{4}-[0-9]{2}$')
);

-- Auto-create a standard user profile after signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.user_profiles (user_id, email, role)
  values (new.id, new.email, 'user')
  on conflict (user_id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.user_profiles enable row level security;
alter table public.finance_records enable row level security;

-- Users can read only their own profile; admins can read profile directory.
-- SECURITY DEFINER helper avoids recursive RLS evaluation on user_profiles.
create or replace function public.is_current_user_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_profiles p
    where p.user_id = auth.uid() and p.role = 'admin'
  );
$$;

drop policy if exists "profile_select_self_or_admin" on public.user_profiles;
create policy "profile_select_self_or_admin"
on public.user_profiles for select
to authenticated
using (auth.uid() = user_id or public.is_current_user_admin());

-- Users can read/insert/update/delete only their own finance records.
-- Admin is deliberately NOT granted access to other users' financial data.
drop policy if exists "finance_select_own" on public.finance_records;
create policy "finance_select_own"
on public.finance_records for select
to authenticated using (auth.uid() = user_id);

drop policy if exists "finance_insert_own" on public.finance_records;
create policy "finance_insert_own"
on public.finance_records for insert
to authenticated with check (auth.uid() = user_id);

drop policy if exists "finance_update_own" on public.finance_records;
create policy "finance_update_own"
on public.finance_records for update
to authenticated using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "finance_delete_own" on public.finance_records;
create policy "finance_delete_own"
on public.finance_records for delete
to authenticated using (auth.uid() = user_id);

create index if not exists finance_records_user_month_idx
on public.finance_records(user_id, record_month desc);

